-- Helper: updated_at trigger
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- Helper: check if JWT belongs to NexusTekFusion admin/staff
create or replace function public.is_ntf_admin()
returns boolean
language sql
stable
as $$
  select coalesce(
    (auth.jwt() ->> 'email') in ('info.nexustekfusion@gmail.com', 'info@nexustekfusion.in')
    or (auth.jwt() -> 'app_metadata' ->> 'role') in ('super_admin', 'admin', 'sales_manager', 'accounts_manager', 'product_manager', 'support_manager'),
    false
  );
$$;

